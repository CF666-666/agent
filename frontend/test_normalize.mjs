var hde = function(e) {
  return e && e.replace(/(^|\n)(#{1,6})([^\s#])/g, "$1$2 $3");
};
var gde = function(e) {
  return e && e.replace(/\*\*([\s\S]+?)\*\*/g, function(t, n) { return n.length > 32 ? n : t; });
};

var raw = `发现变压器漏油时，需要立即采取应急处置措施，防止事态扩大并确保安全。

###一、应急处置措施发现漏油后，应按照以下步骤操作：
- **评估油位**：若漏油导致油位低于最低刻度（例如低于-20℃对应的油位线），应立即申请停运。
- **控制扩散**：设置围油堤（尤其在户外站）防止油扩散，并使用吸油毡覆盖漏油区域。
- **确保安全**：严禁明火，保持现场通风，确保油气浓度低于0.2%LEL（爆炸下限）。操作人员需穿戴防油手套和护目镜进行初步堵漏。

###二、后续维修处理对于特定部件的渗漏，需要更专业的处理：
-如果漏油涉及套管或阀门根部等位置，需要在**停电后**更换密封圈。密封圈应选用耐油橡胶，压缩率控制在15%至25%之间。`;

var n1 = hde(raw);
console.log("after hde:\n" + n1);
console.log("--- still has ###紧贴: " + /\n?#{1,6}[^\s#]/.test(n1));
var n2 = gde(n1);
console.log("\nafter gde:\n" + n2);
